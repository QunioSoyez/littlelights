"""
Import Build a Scene art into Little Lights.

Usage (from the littlelights_app folder):
    python scripts/import-scenes.py ../sources/scenes

Each scene is a folder in sources/scenes/ with:
    background.jpg      the scene (landscape, about 1600 x 1000)
    scene.json          title + sticker list (file, label, size)
    *.png               stickers with see-through backgrounds

Creates:
    assets/scenes/<scene>/...   pictures resized for the app
    src/content/scenes.ts       scene + sticker list (generated)

Needs Python 3 with Pillow (pip install pillow). Safe to re-run.
"""
import json
import os
import shutil
import sys

from PIL import Image

SCENE_ORDER = ["market", "ark", "manger"]  # shown in this order; other scenes follow A-Z
BG_MAX_WIDTH = 1600
STICKER_MAX = 512

src_root = sys.argv[1] if len(sys.argv) > 1 else "../sources/scenes"
app_dir = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
out_root = os.path.join(app_dir, "assets", "scenes")

folders = [f for f in os.listdir(src_root) if os.path.isfile(os.path.join(src_root, f, "scene.json"))]
folders.sort(key=lambda f: (SCENE_ORDER.index(f) if f in SCENE_ORDER else len(SCENE_ORDER), f))

if os.path.isdir(out_root):
    try:
        shutil.rmtree(out_root)  # start clean so removed stickers don't linger
    except OSError:
        print("  (couldn't clear assets/scenes first - old files are overwritten instead)")

scenes = []
for sid in folders:
    src = os.path.join(src_root, sid)
    out = os.path.join(out_root, sid)
    os.makedirs(out, exist_ok=True)
    meta = json.load(open(os.path.join(src, "scene.json"), encoding="utf-8"))

    bg = Image.open(os.path.join(src, "background.jpg")).convert("RGB")
    if bg.width > BG_MAX_WIDTH:
        bg = bg.resize((BG_MAX_WIDTH, round(bg.height * BG_MAX_WIDTH / bg.width)), Image.LANCZOS)
    bg.save(os.path.join(out, "background.jpg"), quality=82, optimize=True, progressive=True)

    stickers = []
    for s in meta["stickers"]:
        path = os.path.join(src, s["file"])
        if not os.path.exists(path):
            print(f"  (missing sticker {sid}/{s['file']} - skipped)")
            continue
        im = Image.open(path).convert("RGBA")
        box = im.getbbox()  # trim empty see-through edges
        if box:
            im = im.crop(box)
        im.thumbnail((STICKER_MAX, STICKER_MAX), Image.LANCZOS)
        name = os.path.splitext(s["file"])[0]
        im.save(os.path.join(out, name + ".png"), optimize=True)
        stickers.append({"id": name, "label": s["label"], "size": s.get("size", 0.15), "w": im.width, "h": im.height})

    scenes.append({"id": sid, "title": meta["title"], "bg": (bg.width, bg.height), "stickers": stickers})
    print(f"{sid}: {meta['title']} - {len(stickers)} stickers")

# Generated TypeScript: require() every picture so they're bundled (works offline)
L = [
    "// GENERATED by scripts/import-scenes.py - do not edit by hand.",
    "// Edit sources/scenes/<scene>/scene.json and the pictures, then re-run the script.",
    'import type { ImageSource } from "expo-image";',
    "",
    "export type SceneSticker = {",
    "  id: string;",
    "  label: string;",
    "  size: number; // width as a share of the scene width",
    "  aspect: number; // width / height",
    "  image: ImageSource;",
    "};",
    "",
    "export type Scene = {",
    "  id: string;",
    "  title: string;",
    "  aspect: number; // background width / height",
    "  background: ImageSource;",
    "  stickers: SceneSticker[];",
    "};",
    "",
    "export const scenes: Scene[] = [",
]
for sc in scenes:
    L.append("  {")
    L.append(f'    id: {json.dumps(sc["id"])},')
    L.append(f'    title: {json.dumps(sc["title"])},')
    L.append(f'    aspect: {sc["bg"][0] / sc["bg"][1]:.4f},')
    L.append(f'    background: require("../../assets/scenes/{sc["id"]}/background.jpg"),')
    L.append("    stickers: [")
    for st in sc["stickers"]:
        L.append(
            f'      {{ id: {json.dumps(st["id"])}, label: {json.dumps(st["label"])}, size: {st["size"]}, '
            f'aspect: {st["w"] / st["h"]:.4f}, image: require("../../assets/scenes/{sc["id"]}/{st["id"]}.png") }},'
        )
    L.append("    ],")
    L.append("  },")
L.append("];")
L.append("")
L.append("export function getScene(id: string): Scene | undefined {")
L.append("  return scenes.find((s) => s.id === id);")
L.append("}")
with open(os.path.join(app_dir, "src", "content", "scenes.ts"), "w", encoding="utf-8") as f:
    f.write("\n".join(L) + "\n")
print(f"Scenes: {len(scenes)}")
