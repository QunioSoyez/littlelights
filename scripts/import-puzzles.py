"""
Import puzzle pictures into Little Lights.

Usage (from the littlelights_app folder):
    python scripts/import-puzzles.py ../sources/puzzles

Each puzzle is a folder in sources/puzzles/ with:
    picture.jpg     the puzzle picture (landscape 4:3, 1600 x 1200)
    puzzle.json     {"title": "...", "cols": 4, "rows": 3}

Creates:
    assets/puzzles/<puzzle>.jpg     picture resized for the app
    src/content/puzzles.ts          puzzle list (generated)

Needs Python 3 with Pillow (pip install pillow). Safe to re-run.
"""
import json
import os
import sys

from PIL import Image

PUZZLE_ORDER = ["noahs-ark", "the-manger", "at-the-market"]  # shown in this order; others follow A-Z
MAX_WIDTH = 1600

src_root = sys.argv[1] if len(sys.argv) > 1 else "../sources/puzzles"
app_dir = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
out_dir = os.path.join(app_dir, "assets", "puzzles")
os.makedirs(out_dir, exist_ok=True)

folders = [f for f in os.listdir(src_root) if os.path.isfile(os.path.join(src_root, f, "puzzle.json"))]
folders.sort(key=lambda f: (PUZZLE_ORDER.index(f) if f in PUZZLE_ORDER else len(PUZZLE_ORDER), f))

puzzles = []
for pid in folders:
    meta = json.load(open(os.path.join(src_root, pid, "puzzle.json"), encoding="utf-8"))
    im = Image.open(os.path.join(src_root, pid, "picture.jpg")).convert("RGB")
    if im.width > MAX_WIDTH:
        im = im.resize((MAX_WIDTH, round(im.height * MAX_WIDTH / im.width)), Image.LANCZOS)
    im.save(os.path.join(out_dir, pid + ".jpg"), quality=85, optimize=True, progressive=True)
    puzzles.append({"id": pid, "title": meta["title"], "cols": int(meta["cols"]), "rows": int(meta["rows"]), "w": im.width, "h": im.height})
    print(f"{pid}: {meta['title']} - {meta['cols']} x {meta['rows']} = {int(meta['cols']) * int(meta['rows'])} pieces")

L = [
    "// GENERATED by scripts/import-puzzles.py - do not edit by hand.",
    "// Edit sources/puzzles/<puzzle>/puzzle.json and picture.jpg, then re-run the script.",
    'import type { ImageSource } from "expo-image";',
    "",
    "export type Puzzle = {",
    "  id: string;",
    "  title: string;",
    "  cols: number; // pieces across",
    "  rows: number; // pieces down",
    "  aspect: number; // picture width / height",
    "  image: ImageSource;",
    "};",
    "",
    "export const puzzles: Puzzle[] = [",
]
for p in puzzles:
    L.append(
        f'  {{ id: {json.dumps(p["id"])}, title: {json.dumps(p["title"])}, cols: {p["cols"]}, rows: {p["rows"]}, '
        f'aspect: {p["w"] / p["h"]:.4f}, image: require("../../assets/puzzles/{p["id"]}.jpg") }},'
    )
L += ["];", "", "export function getPuzzle(id: string): Puzzle | undefined {", "  return puzzles.find((p) => p.id === id);", "}"]
with open(os.path.join(app_dir, "src", "content", "puzzles.ts"), "w", encoding="utf-8") as f:
    f.write("\n".join(L) + "\n")
print(f"Puzzles: {len(puzzles)}")
