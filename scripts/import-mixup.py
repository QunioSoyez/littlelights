"""
Import Story Mix-Up rounds into Little Lights.

Usage (from the littlelights_app folder):
    python scripts/import-mixup.py ../sources/mixup

Each round is a folder in sources/mixup/ with:
    round.json      {"title": "Noah", "level": "easy", "stories": ["ot-02"],
                     "cards": [{"image": "1.jpg", "label": "Noah builds the ark"}, ...]}
                    level: "easy" (one story, 3 cards) or "harder". stories: Bible story ids for the
                    "Read the story" button (see src/content/lathbury.json). List the cards IN THE RIGHT ORDER (3 to 6).
    1.jpg, 2.jpg..  the card pictures (upright 3:4, 600 x 800; other shapes get trimmed from the middle)

Creates:
    assets/mixup/<round>-<n>.jpg    card pictures sized for the app
    src/content/mixup.ts            round list (generated)

Needs Python 3 with Pillow (pip install pillow). Safe to re-run.
"""
import json
import os
import sys

from PIL import Image

# Shown in this order (easy rounds first, then harder ones); rounds not listed follow A-Z
ROUND_ORDER = [
    "noah", "jonah", "david-and-goliath", "daniel", "jesus-is-born", "jesus-calms-the-storm",
    "big-story", "joseph", "moses", "david", "young-jesus", "jesus-helps", "easter",
]
CARD_W, CARD_H = 450, 600  # size used in the app (cards show at most ~220 px wide)

src_root = sys.argv[1] if len(sys.argv) > 1 else "../sources/mixup"
app_dir = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
out_dir = os.path.join(app_dir, "assets", "mixup")
os.makedirs(out_dir, exist_ok=True)


def card_picture(path):
    """Trim to 3:4 from the middle, then resize to the app size."""
    im = Image.open(path).convert("RGB")
    w, h = im.size
    if w / h > CARD_W / CARD_H:  # too wide
        nw = round(h * CARD_W / CARD_H)
        im = im.crop(((w - nw) // 2, 0, (w - nw) // 2 + nw, h))
    else:  # too tall
        nh = round(w * CARD_H / CARD_W)
        im = im.crop((0, (h - nh) // 2, w, (h - nh) // 2 + nh))
    return im.resize((CARD_W, CARD_H), Image.LANCZOS)


folders = [f for f in os.listdir(src_root) if os.path.isfile(os.path.join(src_root, f, "round.json"))]
folders.sort(key=lambda f: (ROUND_ORDER.index(f) if f in ROUND_ORDER else len(ROUND_ORDER), f))

lathbury = json.load(open(os.path.join(app_dir, "src", "content", "lathbury.json"), encoding="utf-8"))
story_ids = {st["id"] for st in lathbury["stories"]}

rounds = []
for rid in folders:
    meta = json.load(open(os.path.join(src_root, rid, "round.json"), encoding="utf-8"))
    cards = meta["cards"]
    if not 3 <= len(cards) <= 6:
        sys.exit(f"{rid}: needs 3 to 6 cards (has {len(cards)})")
    level = meta.get("level", "easy")
    if level not in ("easy", "harder"):
        sys.exit(f"{rid}: level must be \"easy\" or \"harder\"")
    stories = meta.get("stories", [])
    for sid in stories:
        if sid not in story_ids:
            sys.exit(f"{rid}: unknown story id {sid!r}")
    out_cards = []
    for n, c in enumerate(cards, 1):
        name = f"{rid}-{n}.jpg"
        card_picture(os.path.join(src_root, rid, c["image"])).save(
            os.path.join(out_dir, name), quality=85, optimize=True, progressive=True
        )
        out_cards.append({"label": c["label"], "file": name})
    rounds.append({"id": rid, "title": meta["title"], "level": level, "stories": stories, "cards": out_cards})
    print(f"{rid}: {meta['title']} ({level}) - {len(cards)} cards")

L = [
    "// GENERATED by scripts/import-mixup.py - do not edit by hand.",
    "// Edit sources/mixup/<round>/round.json and the card pictures, then re-run the script.",
    'import type { ImageSource } from "expo-image";',
    "",
    "export type MixupCard = { label: string; image: ImageSource };",
    "export type MixupRound = {",
    "  id: string;",
    "  title: string;",
    '  level: "easy" | "harder";',
    "  stories: string[]; // Bible story ids for the \"Read the story\" button",
    "  cards: MixupCard[]; // in the right order",
    "};",
    "",
    "export const mixupRounds: MixupRound[] = [",
]
for r in rounds:
    L.append(
        f"  {{ id: {json.dumps(r['id'])}, title: {json.dumps(r['title'])}, level: {json.dumps(r['level'])}, "
        f"stories: {json.dumps(r['stories'])}, cards: ["
    )
    for c in r["cards"]:
        L.append(f'    {{ label: {json.dumps(c["label"], ensure_ascii=False)}, image: require("../../assets/mixup/{c["file"]}") }},')
    L.append("  ] },")
L += [
    "];",
    "",
    "export function getMixupRound(id: string): MixupRound | undefined {",
    "  return mixupRounds.find((r) => r.id === id);",
    "}",
]
with open(os.path.join(app_dir, "src", "content", "mixup.ts"), "w", encoding="utf-8") as f:
    f.write("\n".join(L) + "\n")
print(f"Rounds: {len(rounds)}")
